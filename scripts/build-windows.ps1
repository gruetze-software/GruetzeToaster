param([switch]$SelfContained)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
$project = Join-Path $repoRoot 'GruetzeToaster/GruetzeToaster.csproj'
$output = Join-Path $repoRoot 'artifacts/windows-local'
$publishArgs = @('publish', $project, '-c', 'Release', '-o', $output, '-p:PublishSingleFile=false')
if ($SelfContained) { $publishArgs += @('-r', 'win-x64', '--self-contained', 'true') }
else { $publishArgs += @('--self-contained', 'false') }
& dotnet @publishArgs
if ($LASTEXITCODE -ne 0) { throw 'Publish failed.' }
Copy-Item -LiteralPath (Join-Path $output 'gruetzetoaster.exe') -Destination (Join-Path $output 'gruetzetoaster.scr')
Copy-Item -LiteralPath (Join-Path $repoRoot 'README.md'), (Join-Path $repoRoot 'LICENSE'), (Join-Path $repoRoot 'THIRD-PARTY-NOTICES.md') -Destination $output
New-Item -ItemType Directory -Force (Join-Path $output 'docs') | Out-Null
Copy-Item -LiteralPath (Join-Path $repoRoot 'docs/ARTWORK-RIGHTS.md') -Destination (Join-Path $output 'docs/ARTWORK-RIGHTS.md')
Copy-Item -LiteralPath (Join-Path $repoRoot 'docs/artwork-prompts.json') -Destination (Join-Path $output 'docs/artwork-prompts.json')
Copy-Item -LiteralPath (Join-Path $repoRoot 'docs/PERFORMANCE.md') -Destination (Join-Path $output 'docs/PERFORMANCE.md')
$modes = @{ 'Settings'='--settings'; 'About'='--about'; 'Windowed'='--windowed'; 'Fullscreen'='--fullscreen' }
foreach ($entry in $modes.GetEnumerator()) {
    $launcher = "@echo off`r`nstart `"`" `"%~dp0gruetzetoaster.exe`" " + $entry.Value + "`r`n"
    [IO.File]::WriteAllText((Join-Path $output ($entry.Key + '.cmd')), $launcher, [Text.Encoding]::ASCII)
}
# Remove launchers generated by older localized builds.
foreach ($legacyName in @('Einstellungen.cmd', 'Info.cmd', 'Fenstermodus.cmd', 'Vollbild.cmd')) {
    $legacyPath = Join-Path $output $legacyName
    if (Test-Path -LiteralPath $legacyPath -PathType Leaf) { Remove-Item -LiteralPath $legacyPath }
}
Write-Host "Local build: $output"
Write-Host 'Open Settings.cmd or Windowed.cmd to begin.'
